#!/usr/bin/env python3
"""Generate crates/app-shell/src/ui/lucide.rs: every Lucide icon as path data,
by its Lucide name, for `ui::named_icon` (feature `icons`).

    python3 scripts/lucide.py <lucide checkout>/packages/dioxus/src

Reads lucide-dioxus's generated components (FastTrackStudios/lucide, tag
fts-upstream-2026-11) and turns each shape into a path: app-shell's icons
are paths only, so no other dioxus is linked to draw them. Lucide is ISC
(see NOTICE).
"""
import os, re, sys

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), '..', 'crates', 'app-shell', 'src', 'ui', 'lucide.rs')
SHAPE = re.compile(r'\b(path|circle|ellipse|line|polyline|polygon|rect)\s*\{([^{}]*)\}', re.S)
ATTR = re.compile(r'"([a-z0-9-]+)":\s*"([^"]*)"')

def num(a, k, d='0'):
    return float(a.get(k, d))

def fmt(x):
    s = ('%.4f' % x).rstrip('0').rstrip('.')
    return '0' if s == '-0' else s

def to_path(kind, a):
    if kind == 'path':
        return a['d']
    if kind in ('circle', 'ellipse'):
        cx, cy = num(a, 'cx'), num(a, 'cy')
        rx = num(a, 'r') if kind == 'circle' else num(a, 'rx')
        ry = num(a, 'r') if kind == 'circle' else num(a, 'ry')
        return (f'M{fmt(cx - rx)} {fmt(cy)}a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(2 * rx)} 0'
                f'a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(-2 * rx)} 0')
    if kind == 'line':
        return f'M{a["x1"]} {a["y1"]}L{a["x2"]} {a["y2"]}'
    if kind in ('polyline', 'polygon'):
        pts = a['points'].replace(',', ' ').split()
        pairs = [f'{pts[i]} {pts[i + 1]}' for i in range(0, len(pts) - 1, 2)]
        return 'M' + 'L'.join(pairs) + ('Z' if kind == 'polygon' else '')
    if kind == 'rect':
        x, y, w, h = num(a, 'x'), num(a, 'y'), num(a, 'width'), num(a, 'height')
        rx = num(a, 'rx', a.get('ry', '0'))
        ry = num(a, 'ry', a.get('rx', '0'))
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if rx == 0 and ry == 0:
            return f'M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z'
        return (f'M{fmt(x + rx)} {fmt(y)}h{fmt(w - 2 * rx)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(ry)}'
                f'v{fmt(h - 2 * ry)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(ry)}'
                f'h{fmt(-(w - 2 * rx))}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(-ry)}'
                f'v{fmt(-(h - 2 * ry))}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(-ry)}Z')
    raise ValueError(kind)

icons = []
for f in sorted(os.listdir(src)):
    if not f.endswith('.rs') or f in ('lib.rs', 'mod.rs'):
        continue
    text = open(os.path.join(src, f)).read()
    body = text[text.find('"stroke-linejoin"'):]
    paths = [to_path(k, dict(ATTR.findall(attrs))) for k, attrs in SHAPE.findall(body)]
    if paths:
        icons.append((f[:-3].replace('_', '-'), paths))

with open(out, 'w') as o:
    o.write('//! Every Lucide icon by its name, as path data (feature `icons`).\n'
            '//! Generated by `scripts/lucide.py`; do not edit. Lucide is ISC\n'
            '//! (NOTICE).\n\n'
            'use super::icons::Icon;\n\n'
            '/// Lucide\'s icon `name` (`"file-text"`, `"house"`), if it has one.\n'
            '#[must_use]\n'
            '#[allow(clippy::too_many_lines)]\n'
            'pub fn lucide(name: &str) -> Option<Icon> {\n'
            '    Some(match name {\n')
    for name, paths in icons:
        ps = ', '.join('"%s"' % p for p in paths)
        o.write(f'        "{name}" => Icon(&[{ps}]),\n')
    o.write('        _ => return None,\n    })\n}\n')
print(len(icons), 'icons')
